/* ============================================================
 * 큰 각도는 한 번에 '쭉' 돌린다 - 연속 스윕 회전 (2026-08-09j 신규)
 *
 * 사용자 요청: "제자리 회전을 툭.툭. 끊지 말고 연속으로."
 *
 * 왜 지금까지 못 했나:
 *   라이다 1회전이 102ms 다. 실측 각속도 94deg/s 로 계속 돌면 한 바퀴 도는 동안
 *   로봇이 9.6도 돌아, 스캔의 앞부분과 뒷부분이 9.6도 어긋난 채 한 장으로 합쳐진다
 *   (1m 거리 점이 168mm 밀림). 그 스캔으로 매칭하면 자세추정이 무너진다.
 *   그래서 "돌고 -> 멈추고 -> 깨끗한 스캔 찍고 -> 또 돌고"를 반복해 왔다.
 *
 * 해결의 열쇠는 '회전 중에 스캔을 안 쓰면 된다'는 것이었다.
 *   1) 목표 각도의 80%를 한 번에 연속으로 돌린다 (스윕). 이 동안 스캔은 버린다.
 *   2) 멈추고, 정지 상태에서 깨끗한 스캔을 한 장 찍는다.
 *   3) 스캔매칭에 "방금 S 라디안 돌았다"를 오도메트리 예측으로 넘긴다.
 *      -> 예측 자체가 이미 S 만큼 돌아가 있으므로, 탐색창은 각속도 추정오차
 *         (실측 ±20%)만 덮으면 된다. 80도 스윕이면 ±16도로 ±25도 창 안이다.
 *   4) 남은 각도는 예전처럼 닫힌 루프로 마무리한다.
 *
 * 왜 80%인가: 실제 각속도가 추정보다 최대 1.25배 빠를 수 있으므로(로그에서
 * 76~116deg/s 관측), 0.8배만 명령하면 최악의 경우에도 목표를 넘지 않는다.
 * 넘어가면 반대로 되돌려야 해서 오히려 느려진다.
 *
 * 시간: 90도 기준 스윕 72도(0.77s) + 정지관측(0.27s) + 마무리 1~2스텝(0.46~0.92s)
 *       = 약 1.5~2.0초. 예전 6스텝 x 0.46 = 2.8초 대비 30~45% 단축이고,
 *       무엇보다 '한 번에 쭉 도는' 동작이라 보기에도 자연스럽다.
 *
 * 안전: 스윕 전에 '그 각도만큼 돌아도 되는지'를 직사각형 기준으로 검사하고
 * (robot_runner__rotation_is_safe), 안 되면 스윕을 건너뛰고 기존 방식으로 간다.
 * 스윕 중에는 눈을 감고 있으므로 이 검사가 유일한 안전장치다 - 그래서 여유를
 * 평소(15mm)보다 크게(25mm) 요구한다.
 * ============================================================ */
#define SWEEP_MIN_DEG   40.0   /* 이보다 작은 회전은 스윕 이득이 없음 */
#define SWEEP_FRACTION  0.80   /* 각속도 추정오차를 감안한 안전계수 */
#define SWEEP_MARGIN_M  0.025  /* 스윕 중엔 관측을 못 하므로 여유를 더 요구 */

/* ============================================================
 * 스윕 상한 (2026-08-10 추가) *** 실기 실패의 최초 방아쇠 ***
 *
 * 실기 로그:
 *     [nav] 연속 회전: +118deg 를 한 번에 돌립니다 (1.80s, 각속도 66deg/s)
 *     [nav] 연속 회전 결과: 61deg 돌았습니다 (명령 1.80s) -> 각속도 실측 34deg/s
 *
 * 118도를 눈 감고 돌라고 명령했는데 실제로는 61도만 돌았다. 즉 각속도 추정이
 * 2배 틀렸다. 그러면 스윕 직후 예측자세는 실제보다 57도 앞서 있는데,
 * 스캔매칭 각도 탐색창은 +-25도뿐이다. 정답이 창 밖이므로 매칭은 창 가장자리를
 * 고를 수밖에 없고, 그 순간부터 자세추정이 통째로 무너진다.
 * (그 뒤 로그가 정확히 그 경로다: 회전중심 진단 149mm 이탈 -> 위치 재탐색이
 *  140mm 순간이동 -> 통로에 있는 로봇이 슬롯 안에 있다고 믿음 -> 헛주차)
 *
 * 원래 주석은 "실제 각속도가 추정보다 최대 1.25배 빠를 수 있으므로 0.8배만
 * 명령한다"였다. 실측은 0.5배로 '느린' 쪽으로 2배 틀렸다 - 가정이 깨졌다.
 * 가정을 고치는 대신, 가정이 깨져도 복구 가능하도록 구조를 바꾼다.
 *   (1) 한 번에 눈 감고 도는 각도를 제한한다. 50도면 2배 오차라도 잔차 25도라
 *       탐색창 안에 들어온다.
 *   (2) 스윕 직후 한 스텝은 탐색창을 스윕 크기에 비례해 넓힌다.
 *   (3) 각속도 추정이 아직 안 익었으면(실측 3회 미만) 스윕을 아예 안 한다.
 * 118도는 50도 스윕 3번으로 나뉘고, 각 스윕 사이에 정지 관측이 들어가므로
 * 추정이 틀려도 그 자리에서 바로잡힌다.
 * ============================================================ */
/* 50 -> 35 (2026-08-10e).
 * 스윕은 눈을 감고 도는 구간이라, 각속도 추정이 틀린 만큼이 그대로 예측오차가
 * 되어 다음 스텝의 스캔매칭 각도창(+-25도) 안에 남아야 한다.
 * 실측 상 각속도는 최대 1.6배까지 어긋나므로 잔차는 0.6 x 스윕각이고,
 *   0.6 x 50도 = 30도 > 25도  (창 밖 - 복구 불가)
 *   0.6 x 35도 = 21도 < 25도  (창 안  - 다음 스텝에서 바로 잡힘)
 * 실기 로그에서 대기점 도착 직후의 -50도 스윕 한 번이 자세를 통째로 무너뜨렸다:
 *   [nav] 연속 회전: -50deg 를 한 번에 돌립니다 (0.70s, 71deg/s)
 *   [slam] 주의: 한 스텝에 70mm/5.0deg 이동, 매칭품질 0.46
 * 그 뒤 모든 슬롯 정렬이 잘못된 자세 위에서 이뤄졌다. */
#define SWEEP_MAX_DEG     35.0  /* 한 번에 눈 감고 돌 수 있는 최대 각도 */
#define SWEEP_MIN_UPDATES 3     /* 각속도 실측이 이만큼은 쌓여야 스윕 허용 */

#endif /* ROBOT_POSE_GATE_H */
